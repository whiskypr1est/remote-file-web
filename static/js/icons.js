/**
 * 生成一个 SVG 图标。
 * @param {string} name  图标名（PATHS 的键）
 * @param {string} cls   附加 class
 */
export function icon(name, cls) {
  var body = PATHS[name] || PATHS.file;
  return '<svg viewBox="0 0 24 24" aria-hidden="true"' +
    (cls ? ' class="' + cls + '"' : '') +
    ' fill="currentColor">' + body + '</svg>';
}

/* 文件类型 -> 图标名 */
const TYPE_ICON = {
  folder: 'folder',
  image: 'image',
  document: 'document',
  spreadsheet: 'spreadsheet',
  presentation: 'presentation',
  pdf: 'pdf',
  archive: 'archive',
  video: 'video',
  audio: 'audio',
  code: 'code',
  other: 'file'
};

/** 按文件类型取图标名 */
export function typeIconName(type) {
  return TYPE_ICON[type] || 'file';
}

/** 直接按文件类型生成图标 SVG */
export function fileIcon(type, cls) {
  return icon(typeIconName(type), cls);
}

/* 类型的显示名称（详细列表的「类型」列） */
const TYPE_LABEL = {
  folder: '文件夹',
  image: '图片',
  document: '文档',
  spreadsheet: '工作表',
  presentation: '演示文稿',
  pdf: 'PDF 文档',
  archive: '压缩文件',
  video: '视频',
  audio: '音频',
  code: '代码/文本',
  other: '文件'
};

/** 类型的友好名称；扩展名存在时带上，更接近 Windows 的显示习惯 */
export function typeLabel(type, ext) {
  var base = TYPE_LABEL[type] || '文件';
  if (ext && type !== 'folder') {
    return (ext.replace('.', '').toUpperCase() + ' ' + base).trim();
  }
  return base;
}

export default { icon, fileIcon, typeIconName, typeLabel };
